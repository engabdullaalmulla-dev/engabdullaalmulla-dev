/**
 * Draws the table's textures — the felt weave, the light over it, and the
 * pattern on the back of a card — and writes them into src/ui/textures.ts as
 * data URIs.
 *
 * They live in the source rather than in assets/ so that they survive being
 * packed into a single HTML file, and so nobody has to open an image editor to
 * change the colour of the felt.
 *
 *   node scripts/generate-textures.js
 */

const fs = require('node:fs');
const path = require('node:path');

const { dataUri } = require('./png');

/** A cheap deterministic hash, so the noise is the same on every run. */
function noise(x, y, seed) {
  let h = (x * 374761393 + y * 668265263 + seed * 1274126177) | 0;
  h = (h ^ (h >>> 13)) * 1274126177;
  return ((h ^ (h >>> 16)) >>> 0) / 4294967296;
}

function rgba(pixels, width, x, y, r, g, b, a) {
  const at = (y * width + x) * 4;
  pixels[at] = Math.max(0, Math.min(255, Math.round(r)));
  pixels[at + 1] = Math.max(0, Math.min(255, Math.round(g)));
  pixels[at + 2] = Math.max(0, Math.min(255, Math.round(b)));
  pixels[at + 3] = Math.max(0, Math.min(255, Math.round(a)));
}

/**
 * Paper: fibre and a faint tooth, the way a sheet of good card stock catches
 * the light. It tiles, so the grain has to wrap at the edges.
 */
function paper(size, base) {
  const pixels = Buffer.alloc(size * size * 4);
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      const fibre = (noise(x, y, 7) - 0.5) * 6;
      const clump = (noise(x >> 2, y >> 2, 19) - 0.5) * 4;
      const tooth = Math.sin((x + y) / 3) * 0.8;
      const lift = fibre + clump + tooth;
      rgba(pixels, size, x, y, base[0] + lift, base[1] + lift * 0.95, base[2] + lift * 0.85, 255);
    }
  }
  return dataUri(size, size, pixels);
}

/**
 * Daylight across the table: brightest in the middle, settling into a warm
 * shade at the edges. Kept gentle — this should read as light falling on
 * paper, not as a spotlight.
 */
function daylight(size, tint) {
  const pixels = Buffer.alloc(size * size * 4);
  const centre = (size - 1) / 2;
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      const dx = (x - centre) / centre;
      const dy = (y - centre) / centre;
      const distance = Math.min(1, Math.sqrt(dx * dx + dy * dy) / Math.SQRT2);
      const shade = Math.pow(distance, 2.1) * 46;
      rgba(pixels, size, x, y, tint[0], tint[1], tint[2], shade);
    }
  }
  return dataUri(size, size, pixels);
}

/**
 * The back of a card: a diagonal lattice, the way a deck has had one since
 * long before anyone printed this game.
 */
function cardBack(size, ink, line, glint) {
  const pixels = Buffer.alloc(size * size * 4);
  const pitch = size / 4;
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      const down = Math.abs(((x + y) % pitch) - pitch / 2);
      const up = Math.abs(((x - y + size * 4) % pitch) - pitch / 2);
      const lattice = Math.min(down, up);
      const onLine = Math.max(0, 1 - lattice / 1.2);
      const knot = down < 1 && up < 1 ? 1 : 0;
      const grain = (noise(x, y, 31) - 0.5) * 6;

      const colour = [
        ink[0] + (line[0] - ink[0]) * onLine + (glint[0] - ink[0]) * knot * 0.8 + grain,
        ink[1] + (line[1] - ink[1]) * onLine + (glint[1] - ink[1]) * knot * 0.8 + grain,
        ink[2] + (line[2] - ink[2]) * onLine + (glint[2] - ink[2]) * knot * 0.8 + grain,
      ];
      rgba(pixels, size, x, y, colour[0], colour[1], colour[2], 255);
    }
  }
  return dataUri(size, size, pixels);
}

const textures = {
  PAPER: paper(72, [246, 238, 228]),
  TABLE_LIGHT: daylight(160, [138, 106, 74]),
  CARD_BACK: cardBack(64, [232, 115, 74], [250, 235, 225], [193, 81, 43]),
};

const file = `/**
 * Generated by scripts/generate-textures.js — do not edit by hand.
 *
 * The table's surfaces, as data URIs. They ship inside the JavaScript so that
 * the single-file web build needs nothing from the network.
 */

${Object.entries(textures)
  .map(([name, uri]) => `export const ${name} = '${uri}';`)
  .join('\n\n')}
`;

const out = path.join(__dirname, '..', 'src', 'ui', 'textures.ts');
fs.writeFileSync(out, file);
const kb = (file.length / 1024).toFixed(0);
console.log(`wrote src/ui/textures.ts — ${kb} KB`);
for (const [name, uri] of Object.entries(textures)) {
  console.log(`  ${name}: ${(uri.length / 1024).toFixed(1)} KB`);
}
